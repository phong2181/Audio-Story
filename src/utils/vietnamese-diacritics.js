/**
 * Restore Vietnamese diacritics for text that has lost its tone marks.
 * Uses WORD_DICT for common words and AMBIGUOUS_WORDS for context-aware disambiguation.
 * 
 * @param {string} text - Input text (may or may not have diacritics)
 * @returns {string} - Text with Vietnamese diacritics restored
 */
export function restoreDiacritics(text) {
    if (!text || typeof text !== 'string') return text;
    
    // Tokenize: split by word boundaries, keeping punctuation and spaces
    const tokens = text.split(/\b/);
    const result = tokens.map(token => {
        const trimmed = token.trim();
        if (!trimmed) return token;
        
        // Skip if token already has Vietnamese diacritics
        const hasDiacritics = /[àáảãạăằắẳẵặâầấẩẫậèéẻẽẹêềếểễệìíỉĩịòóỏõọôồốổỗộơờớởỡợùúủũụưừứửữựỳýỷỹỵđ]/i.test(trimmed);
        if (hasDiacritics) return token;
        
        const lowerToken = trimmed.toLowerCase();
        
        // Check ambiguous words first
        if (AMBIGUOUS_WORDS[lowerToken]) {
            const entry = AMBIGUOUS_WORDS[lowerToken];
            let bestMatch = entry.default;
            
            // Try to find context match
            for (const rule of entry.rules) {
                // Check if any context word appears in the text
                const contextFound = rule.context.some(ctxWord => {
                    const ctxRegex = new RegExp(`\\b${ctxWord}\\b`, 'i');
                    return ctxRegex.test(text);
                });
                if (contextFound) {
                    bestMatch = rule.form;
                    break;
                }
            }
            
            // Preserve original case pattern
            if (trimmed[0] === trimmed[0].toUpperCase()) {
                return bestMatch.charAt(0).toUpperCase() + bestMatch.slice(1);
            }
            return bestMatch;
        }
        
        // Check main dictionary
        if (WORD_DICT.has(lowerToken)) {
            const diacriticForm = WORD_DICT.get(lowerToken);
            // Preserve original case pattern
            if (trimmed[0] === trimmed[0].toUpperCase()) {
                return diacriticForm.charAt(0).toUpperCase() + diacriticForm.slice(1);
            }
            return diacriticForm;
        }
        
        return token;
    });
    
    return result.join('');
}
